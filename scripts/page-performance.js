'use strict';

const crypto = require('node:crypto');
const { text: readText } = require('node:stream/consumers');

const assetType = /\.(?:css|js|woff2?|ttf|otf|png|jpe?g|webp|gif|svg|ico|avif)$/i;
const version = data => crypto.createHash('sha256').update(data).digest('hex').slice(0, 16);

function assetUrl(value, owner, hashes, origin) {
  if (!value || /^(?:data:|blob:|#|\/\/)/i.test(value)) return value;
  const decoded = value.replace(/&amp;/g, '&');
  let url;
  try { url = new URL(decoded, `${origin}/${owner}`); } catch { return value; }
  if (url.origin !== origin) return value;
  let name;
  try { name = decodeURIComponent(url.pathname).slice(1); } catch { return value; }
  const hash = hashes.get(name);
  if (!hashes.has(name)) return value;
  if (hash) url.searchParams.set('v', hash);
  else if (/^[0-9a-f]{16}$/.test(url.searchParams.get('v') || '')) url.searchParams.delete('v');
  else return value;
  // Keep relative paths, escaped filenames and fragments as written.
  const base = decoded.split(/[?#]/, 1)[0];
  return base + url.search + url.hash;
}

function versionCss(css, owner, hashes, origin) {
  return css.replace(/url\(\s*(["']?)([^\s"')]+)\1\s*\)/gi, (match, quote, url) =>
    `url(${quote}${assetUrl(url, owner, hashes, origin)}${quote})`);
}

function versionTag(tag, owner, hashes, origin) {
  return tag.replace(/(\s(?:src|data-src|href)\s*=\s*)(["'])(.*?)\2/gi, (match, before, quote, url) => {
    const updated = assetUrl(url, owner, hashes, origin);
    return updated === url ? match : before + quote + updated.replace(/&/g, '&amp;') + quote;
  });
}

function versionHtml(html, owner, hashes, origin) {
  // Do not serialize the document: preserve text, entities, attributes and code.
  return html.replace(/<!--[\s\S]*?-->|<style\b[^>]*>[\s\S]*?<\/style\s*>|<script\b[^>]*>[\s\S]*?<\/script\s*>|<(?:img|source|link)\b[^>]*>/gi, block => {
    if (/^<!--|^<style\b/i.test(block)) return block;
    if (/^<script\b/i.test(block)) {
      const end = block.indexOf('>') + 1;
      const tag = versionTag(block.slice(0, end), owner, hashes, origin);
      const content = block.slice(end);
      if (/\btype\s*=\s*["']application\/(?:ld\+)?json/i.test(tag)) return tag + content;
      // Theme loaders use quoted root-relative paths for optional plugins.
      return tag + content.replace(/(["'`])(\/(?:css|js|fonts)\/[^\s"'`<>]+)\1/g, (match, quote, url) =>
        quote + assetUrl(url, owner, hashes, origin) + quote);
    }
    return versionTag(block, owner, hashes, origin);
  });
}

function prioritizeImages(html) {
  const cover = /(<div class="preview cover"[^>]*>\s*)(<img\b[^>]*>)/i;
  const post = /(<div class="post-cover"[^>]*>\s*)(<img\b[^>]*>)/i;
  return html.replace(cover.test(html) ? cover : post, (match, parent, img) => {
    // Before Stellar's lazyload filter: one discoverable primary image per page.
    if (/\bfetchpriority\s*=|\bloading\s*=/i.test(img)) return match;
    return parent + img.replace('<img', '<img no-lazy loading="eager" fetchpriority="high" decoding="async"');
  }).replace(/<!--[\s\S]*?-->|<script\b[^>]*>[\s\S]*?<\/script\s*>|<iframe\b[^>]*>/gi, tag =>
    !/^<iframe\b/i.test(tag) || /\bloading\s*=/i.test(tag) ? tag : tag.replace('<iframe', '<iframe loading="lazy"'));
}

hexo.extend.filter.register('after_render:html', prioritizeImages, 8);

hexo.extend.filter.register('after_generate', async function fingerprintAssets() {
  const origin = new URL(this.config.url).origin;
  const routes = this.route.list();
  const hashes = new Map();
  const cssFiles = routes.filter(name => /\.css$/i.test(name));
  for (const name of cssFiles) hashes.set(name, null);
  // Hash final generated bytes, not source files or the theme version. Streams
  // keep large unchanged images out of memory and do not create duplicate assets.
  for (const name of routes.filter(name => assetType.test(name) && !/\.css$/i.test(name))) {
    const hash = crypto.createHash('sha256');
    for await (const chunk of this.route.get(name)) hash.update(chunk);
    hashes.set(name, hash.digest('hex').slice(0, 16));
  }
  // Fonts/images first, CSS second, HTML last: dependencies change their parent's
  // fingerprint too. CSS imports without a known fingerprint still revalidate.
  for (const name of cssFiles) {
    const original = await readText(this.route.get(name));
    const updated = versionCss(original, name, hashes, origin);
    if (updated !== original) this.route.set(name, updated);
    hashes.set(name, version(updated));
  }
  for (const name of routes.filter(name => /\.html$/i.test(name))) {
    const original = await readText(this.route.get(name));
    const updated = versionHtml(original, name, hashes, origin);
    if (updated !== original) this.route.set(name, updated);
  }
});

module.exports = { assetUrl, versionCss, versionHtml, prioritizeImages, version };
